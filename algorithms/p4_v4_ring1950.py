# -*- coding: utf-8 -*-
"""问题 4 · v4：外环外推 50 m 的稳健布站。

与 v2 的**唯一**差别是外环半径：v1/v2/v3 取 ``ρ = 1900`` m，本版取 ``ρ = 1950`` m。
站数、完备性判据、铺清方式、候选点排序、滚动计价全部沿用 v2，不引入新逻辑。

【为什么要改】
定向源的覆盖半角 α = 90°（总覆盖角 180°），故"某点能否被排除"等价于
**该点处、1000 m 内无信号测站的最大角间隔 g_max ≤ 2α = 180°**。
对该判据做"网格粗筛 + 局部爬山"求真实最坏值（25 站不变）：

    ρ = 1900 m ：真实最坏角间隔 171.80°，裕度  8.20°，最近邻 167.9 m
    ρ = 1950 m ：真实最坏角间隔 161.20°，裕度 18.80°，最近邻 217.9 m
    ρ = 2000 m ：真实最坏角间隔 182.51°，裕度 −2.51°（已失守，不能用）
    ρ = 1870 m ：真实最坏角间隔 178.51°，裕度  1.49°（太险，不能用）

外推 50 m 就把完备性裕度从 8.2° 提到 18.8°，而站数不变、巡访里程几乎不变，
是没有代价的稳健性提升。

【顺带说明一个容易误判的点】
v1/v2/v3 的布站里有 6 对"贴在一起"的测站：内层 1732 m 那一圈
（方位 30°/90°/…/330°）与外环 12 站同方位，相距仅 167.9 m。
把外环旋转半格（相位 15°）可把最近邻拉到 502.5 m，但**最坏角间隔不变**
（仍是 171.80°），且相位 15° 与外推 50 m 叠加反而会失守（−31.01°）。
故本版选择"外推"而不是"旋转"。
"""

from __future__ import annotations

from .base import AlgorithmSpec
from .p4_directional import _inner_lattice, _outer_ring
from .p4_v2_receding import P4V2Hunter


class P4V4Hunter(P4V2Hunter):
    """只改布站：外环半径 1900 m → 1950 m，其余与 v2 完全一致。"""

    DEFAULTS = {
        **P4V2Hunter.DEFAULTS,
        "outer_r": 1950.0,      # 外环半径（v1/v2/v3 用 1900 m）
    }

    def survey_stations(self) -> list[tuple[float, float]]:
        """内层六边形格 13 站（不变）+ 半径 ρ 外环 k 站（默认 ρ=1950、k=12）。"""
        k = int(self.p.get("outer_k", 12))
        rho = float(self.p.get("outer_r", 1950.0))
        pts: list[tuple[float, float]] = [(0.0, 0.0)]
        pts += [q for q in _inner_lattice() if q != (0.0, 0.0)]
        if k > 0:
            pts += _outer_ring(rho, k)
        return pts


